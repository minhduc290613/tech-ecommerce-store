const keys = Object.keys(ENGLISH_ADMIN).sort((a, b) => b.length - a.length);
const replaceText = value => {
  let next = value;
  for (const key of keys) {
    if (next.includes(key)) next = next.split(key).join(ENGLISH_ADMIN[key]);
  }
  return next;
};

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement;
    if (!parent || /^(SCRIPT|STYLE|TEXTAREA|INPUT)$/.test(parent.tagName)) return;
    const next = replaceText(node.nodeValue || "");
    if (next !== node.nodeValue) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const attr of ["placeholder", "title", "aria-label"]) {
    if (node.hasAttribute(attr)) {
      const next = replaceText(node.getAttribute(attr));
      if (next !== node.getAttribute(attr)) node.setAttribute(attr, next);
    }
  }
  node.childNodes.forEach(translateNode);
}

function translateAdmin() {
  if (document.body?.dataset.adminLanguage !== "en") return;
  translateNode(document.querySelector(".admin-shell") || document.body);
}

translateAdmin();
const observer = new MutationObserver(mutations => {
  if (document.body?.dataset.adminLanguage !== "en") return;
  for (const mutation of mutations) {
    mutation.addedNodes.forEach(translateNode);
    if (mutation.type === "characterData") translateNode(mutation.target);
  }
});
observer.observe(document.body, { childList: true, subtree: true, characterData: true });
